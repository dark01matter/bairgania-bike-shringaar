import { serve } from "https://deno.land/std@0.168.0/http/server.ts";

const corsHeaders = {
  "Access-Control-Allow-Origin": "*",
  "Access-Control-Allow-Headers": "authorization, x-client-info, apikey, content-type",
};

const systemPrompt = `You are the AI assistant for Bike Shringaar Bairgania, a premium bike accessories and service center located in Bairgania, Bihar, India. Owner: Anmol Singh. Contact: +91 73198 66462.

Your role is to help customers with:
- Bike accessories recommendations (helmets, gloves, exhausts, lights, mirrors, bags)
- Service inquiries (full service, engine work, custom paint, modifications, electrical, detailing)
- Pricing information and availability
- Booking service appointments
- General bike care tips and advice

Personality:
- Friendly, professional, and knowledgeable
- Mix Hindi and English naturally (Hinglish) to connect with local customers
- Be enthusiastic about bikes and motorcycle culture
- Provide helpful, concise answers
- Encourage customers to visit the shop or call for specific queries

Key info:
- Located in Bairgania, Bihar
- 10+ years of experience
- 5000+ happy customers
- Premium quality accessories
- Expert mechanics for all bike brands

Keep responses conversational and helpful. Use emojis sparingly for warmth.`;

serve(async (req) => {
  if (req.method === "OPTIONS") {
    return new Response(null, { headers: corsHeaders });
  }

  try {
    const { messages } = await req.json();
    const LOVABLE_API_KEY = Deno.env.get("LOVABLE_API_KEY");
    
    if (!LOVABLE_API_KEY) {
      throw new Error("LOVABLE_API_KEY is not configured");
    }

    const response = await fetch("https://ai.gateway.lovable.dev/v1/chat/completions", {
      method: "POST",
      headers: {
        Authorization: `Bearer ${LOVABLE_API_KEY}`,
        "Content-Type": "application/json",
      },
      body: JSON.stringify({
        model: "google/gemini-2.5-flash",
        messages: [
          { role: "system", content: systemPrompt },
          ...messages,
        ],
        stream: true,
      }),
    });

    if (!response.ok) {
      if (response.status === 429) {
        return new Response(JSON.stringify({ error: "Rate limit exceeded. Please try again later." }), {
          status: 429,
          headers: { ...corsHeaders, "Content-Type": "application/json" },
        });
      }
      if (response.status === 402) {
        return new Response(JSON.stringify({ error: "Service temporarily unavailable." }), {
          status: 402,
          headers: { ...corsHeaders, "Content-Type": "application/json" },
        });
      }
      const t = await response.text();
      console.error("AI gateway error:", response.status, t);
      return new Response(JSON.stringify({ error: "AI service error" }), {
        status: 500,
        headers: { ...corsHeaders, "Content-Type": "application/json" },
      });
    }

    return new Response(response.body, {
      headers: { ...corsHeaders, "Content-Type": "text/event-stream" },
    });
  } catch (e) {
    console.error("bike-assistant error:", e);
    return new Response(JSON.stringify({ error: e instanceof Error ? e.message : "Unknown error" }), {
      status: 500,
      headers: { ...corsHeaders, "Content-Type": "application/json" },
    });
  }
});
